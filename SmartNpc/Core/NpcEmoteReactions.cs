    /// <para>「改变姿势」（/pose 切待机站姿的本体动作，loop+start 双行）不是对她做的互动 ——
    /// 玩家随手切站姿她不该接话。曾因名字带"姿势"被扫进训练池（用户实锤台词窜台）。</para>
    /// </summary>
    private static readonly HashSet<string> IgnoredEmotes = new() { "改变姿势" };

    /// <summary>这个动作要不要触发反应（忽略名单里的返回 false）。</summary>
    public static bool IsIgnored(string? emoteName)
        => !string.IsNullOrWhiteSpace(emoteName) && IgnoredEmotes.Contains(emoteName);

    /// <summary>动作名 → 反应分类：<b>细分类优先</b>，落不进再走粗分类，最后 <see cref="NpcLines.React.通用"/>。</summary>
    public static NpcLines.React CategoryOf(string? emoteName)
    {
        if (string.IsNullOrWhiteSpace(emoteName))
            return NpcLines.React.通用;

        // v0.18.64：细分类先行 —— 同一个关键词家族和回应动作表（ResponseRules）保持一致。
        foreach (var (keys, kind) in FineRules)
        {
            foreach (var k in keys)
            {
                if (emoteName!.Contains(k, StringComparison.Ordinal))
                    return kind;
            }
        }

        foreach (var (keys, kind) in Rules)
        {
            foreach (var k in keys)
            {
                if (emoteName!.Contains(k, StringComparison.Ordinal))
                    return kind;
            }
        }

        return NpcLines.React.通用;
    }

