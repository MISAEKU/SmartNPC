    /// <summary>
    /// v0.18.62：玩家的动作名 → 她的<b>回应动作名</b>（语义匹配）。
    ///
    /// <para>① 特例精确表 → ② 有序关键词规则 → ③ 「表情：」脸（负面脸回关心/慌张，
    /// 其余镜面——脸对脸做同一个表情是自然反应，不算盲镜像）→ ④ 兜底「点头」。</para>
    ///
    /// <para>返回的名字保证能在 Emote 表里找到（核查脚本 <c>_re/check_emote_responses.py</c>）。</para>
    /// </summary>
    public static string ResponseEmoteNameFor(string? emoteName)
    {
        if (string.IsNullOrWhiteSpace(emoteName))
            return "点头";

        // ① 特例精确
        if (ExactResponses.TryGetValue(emoteName, out var exact))
            return exact;

        // ② 有序关键词规则
        foreach (var (keys, resp) in ResponseRules)
        {
            foreach (var k in keys)
            {
                if (emoteName.Contains(k, StringComparison.Ordinal))
                    return resp;
            }
        }

        // ③ 「表情：」脸
        if (emoteName.StartsWith("表情：", StringComparison.Ordinal))
        {
            foreach (var k in FaceComfortKeys)
            {
                if (emoteName.Contains(k, StringComparison.Ordinal))
                    return "安抚";
            }
            foreach (var k in FaceStartleKeys)
            {
                if (emoteName.Contains(k, StringComparison.Ordinal))
                    return "慌张";
            }
            // 其余脸 → 镜面（她做同一个表情；名字本身就在表里）
            return emoteName;
        }

        // ④ 兜底：点头（绝不做"她也做同一个动作"的盲镜像）
        return "点头";
    }
