    /// <summary>
    /// 动作名 → 台词分类：<b>覆盖表先行</b>，落不进再走 <see cref="CategoryOf"/>
    /// （细分类 → 粗分类 → 通用）。
    /// </summary>
    public static NpcLines.React KindFor(string? emoteName)
    {
        if (!string.IsNullOrWhiteSpace(emoteName))
        {
            foreach (var (keys, kind) in LineKindRules)
            {
                foreach (var k in keys)
                {
                    if (emoteName.Contains(k, StringComparison.Ordinal))
                        return kind;
                }
            }
        }

        return CategoryOf(emoteName);
    }

    /// <summary>
