    /// <summary>距离池（Idle / Near / Far + 话多密系数）。取不到就退回元气。</summary>
    public static (string[] Idle, string[] Near, string[] Far, float Chatter) Pool(NpcBrain.Persona persona)
    {
        if (!Pools.TryGetValue(persona, out var p))
