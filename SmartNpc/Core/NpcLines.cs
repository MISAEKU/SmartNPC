    /// <summary>
    /// 把台词里的变量换成实际值：<c>{{称谓}}</c> / <c>{天气}</c> / <c>{艾时}</c>。
    ///
    /// <para>称谓留空 / 只有空白时回退 <see cref="DefaultTitle"/>，保证台词里不会出现
    /// 一个突兀的空格或半个变量。</para>
    /// </summary>
    public static string Resolve(string? line, string? title, string? weatherName = null, int hour = -1,
                                 string? actionName = null)
    {
        if (string.IsNullOrEmpty(line))
            return string.Empty;

        var text = line;

        if (text.Contains(TitleToken, StringComparison.Ordinal))
        {
            var use = string.IsNullOrWhiteSpace(title) ? DefaultTitle : title.Trim();
            text = text.Replace(TitleToken, use, StringComparison.Ordinal);
        }

        if (text.Contains(WeatherToken, StringComparison.Ordinal))
        {
            var w = string.IsNullOrWhiteSpace(weatherName) ? "好天气" : weatherName.Trim();
            text = text.Replace(WeatherToken, w, StringComparison.Ordinal);
        }

        if (text.Contains(HourToken, StringComparison.Ordinal))
            text = text.Replace(HourToken, hour >= 0 ? hour.ToString() : "现在这个", StringComparison.Ordinal);

        // v0.18.64：{{动作}} —— 玩家刚做的动作名（表情回应台词用）。
        // 名字插进句子里要自然，模板写成"'{{动作}}'吗"这种带引号/顿号的形式最稳。
        if (text.Contains(ActionToken, StringComparison.Ordinal))
        {
            var a = string.IsNullOrWhiteSpace(actionName) ? "这个动作" : actionName.Trim();
            text = text.Replace(ActionToken, a, StringComparison.Ordinal);
        }

        return text;
    }

    /// <summary>这一套人格总共有多少条独立文本（自检用，面板 / 诊断会显示）。</summary>
    public static int CountFor(NpcBrain.Persona persona)
        => Breakdown(persona).Sum(x => x.Count);

    /// <summary>
    /// 按类别列出条数（v0.18.51，用户要「每个性格的每一类台词分别有多少」）。
    /// 返回的 (类别名, 条数) 顺序固定，可直接画成表。
    /// </summary>
    public static (string Category, int Count)[] Breakdown(NpcBrain.Persona persona)
    {
        var rows = new List<(string, int)>();

        if (Pools.TryGetValue(persona, out var p))
        {
            rows.Add(("闲聊·近距离", p.Idle.Length));
            rows.Add(("闲聊·贴身", p.Near.Length));
            rows.Add(("闲聊·掉队", p.Far.Length));
        }

        if (WeatherNamePools.TryGetValue(persona, out var wn))
            rows.Add(("天气·具名", wn.Length));

        foreach (var kind in Enum.GetValues<Weather>())
        {
            if (kind is Weather.未知 or Weather.其他)
                continue;

            rows.Add(($"天气·{Name(kind)}", WeatherLines(persona, kind)?.Length ?? 0));
        }

        foreach (var phase in Enum.GetValues<DayPhase>())
            rows.Add(($"时段·{Name(phase)}", PhaseLines(persona, phase)?.Length ?? 0));

        foreach (var c in Enum.GetValues<Combat>())
            rows.Add(($"战斗·{Name(c)}", CombatLines(persona, c)?.Length ?? 0));

        foreach (var t in Enum.GetValues<Touch>())
            rows.Add(($"互动·{Name(t)}", TouchLines(persona, t)?.Length ?? 0));

        foreach (var a in Enum.GetValues<Ask>())
            rows.Add(($"问答·{Name(a)}", AskLines(persona, a)?.Length ?? 0));

        foreach (var r in Enum.GetValues<React>())
            rows.Add(($"反应·{r}", ReactLines(persona, r)?.Length ?? 0));

        foreach (var s in Enum.GetValues<NpcBrain.Scene>())
            rows.Add(($"情境·{s}", SceneLines(persona, s)?.Length ?? 0));

        return rows.ToArray();
    }

