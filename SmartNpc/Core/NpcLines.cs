    /// <summary>
    /// 主动问答台词。
    ///
    /// <para>⚠️ 「问时间」需要真实小时数：小时还没取到（-1）时，
    /// 带 <c>{艾时}</c> 的句子念出来会是半个空句，所以这里<b>把它们剔掉</b>，
    /// 只留不依赖小时的那一句。</para>
    /// </summary>
    public static string[]? AskLines(NpcBrain.Persona persona, Ask topic, int hour = -1)
    {
        if (!AskPools.TryGetValue(persona, out var by) || !by.TryGetValue(topic, out var lines))
            return null;

        if (topic == Ask.问时间 && hour < 0)
        {
            var safe = lines.Where(l => !l.Contains(HourToken, StringComparison.Ordinal)).ToArray();
            return safe.Length > 0 ? safe : lines;
        }

        return lines;
    }

