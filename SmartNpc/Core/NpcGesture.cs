/// <summary>
/// 台词 → 表情动作（v0.18.51）。
///
/// <para>⚠️⚠️ 这个文件存在的唯一理由，是修掉一个被用户点名的老毛病：</para>
///
/// <para><b>旧做法</b>：说每一句话都无条件 <c>PlayIdleGesture(人格)</c> ——
/// 从该人格的关键字池里<b>随机</b>挑一个动作。于是出现两个典型事故：</para>
/// <list type="bullet">
/// <item>安静打招呼也附带<b>两次摇头</b>（"摇头"在她的池子里，随机就摇到了）；</item>
/// <item>弱气说"我是来跟着你的……可以吗？"时做了<b>「用触控板记录」</b>——
/// 那是个自拍动作，会因为她的人格池关键字里有"记录"而命中。</item>
/// </list>
///
/// <para><b>新做法</b>：<b>按台词的含义挑动作</b>，而且<b>不是每句都配动作</b> ——</para>
/// <list type="number">
/// <item>拿台词去匹配下面的<b>语义规则表</b>（先命中先得）；</item>
/// <item><b>一条都没命中 ⇒ 只说话，不做动作</b>（这是常态，一大半台词都不该比划）；</item>
/// <item>命中了还要再过两道闸：<see cref="ChancePercent"/>（不是每次都比划）与
/// <see cref="MinGapSeconds"/>（两次动作之间的最小间隔）；</item>
/// <item>动作名只从<b>游戏 Emote 表里真实存在</b>的名字里挑，
/// 对不上就<b>宁可不做</b>（见 <see cref="NpcAnimator.ResolveActionName"/>）。</item>
/// </list>
///
/// <para>⚠️ 规则表里的动作名是"候选"，按优先级排列；运行时先找完全相同的名字，
/// 找不到再找"名字里包含这个词"的（国服表名是中文，这样最不容易空手而归）。
