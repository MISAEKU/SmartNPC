    /// <summary>
    /// 这个动作该播多久（秒）。
    ///
    /// <para>⚠️ 两档都用 <c>Contains</c>：表里真实名字常带后缀（"摇头" / "摇头（慢）"），
    /// 别指望一字不差。长档先判（"张开双臂"含"抱"不会被误判成 quick）。</para>
    /// </summary>
    public static float DurationFor(string? action)
    {
        if (string.IsNullOrWhiteSpace(action))
            return 2.2f;

        foreach (var g in LongGestures)
        {
            if (action!.Contains(g, StringComparison.Ordinal))
                return 2.6f;
        }

        foreach (var g in QuickGestures)
        {
            if (action!.Contains(g, StringComparison.Ordinal))
                return 1.15f;
        }

        return 2.2f;
    }

    /// <summary>把动作表灌进来。必须在插件初始化时调一次（NpcController.Attach）。</summary>
    public static void Initialize(IEnumerable<string>? names)
        => _available = names?.ToArray() ?? [];

    /// <summary>每帧推进动作间隔计时（NpcController 调）。</summary>
    public static void Tick(float deltaTime)
    {
        if (_sinceLastGesture < 1000f)
            _sinceLastGesture += deltaTime;
    }

    /// <summary>
    /// 这句话该配什么动作？返回 null = <b>只说话，不做动作</b>。
    ///
    /// <para>已经把 <see cref="ChancePercent"/> 与 <see cref="MinGapSeconds"/> 两道闸算进去了，
    /// 调用方拿到非 null 就可以直接播。</para>
    ///
    /// <para>v0.18.69.22：<paramref name="chanceOverride"/> 允许按 NPC 覆盖命中概率
    /// （副 NPC 槽位设置；null = 全局 <see cref="ChancePercent"/>。最小间隔仍是全局节奏）。</para>
    /// </summary>
    public static string? Decide(NpcBrain.Persona persona, string line, float? chanceOverride = null)
    {
        if (string.IsNullOrWhiteSpace(line))
            return null;

        var action = Match(line);
        if (action is null)
            return null;

        if (_sinceLastGesture < MinGapSeconds)
            return null;

        if (Rng.Next(100) >= (int)Math.Clamp(chanceOverride ?? ChancePercent, 0f, 100f))
            return null;

        _sinceLastGesture = 0f;
        return action;
    }

    /// <summary>只做"台词 → 动作名"的推导，<b>不过那两道闸</b>（生成对照表 / 诊断用）。</summary>
    public static string? Match(string line)
    {
        if (string.IsNullOrWhiteSpace(line))
            return null;

        foreach (var (keys, actions, not) in Rules)
        {
            // 排除词优先：句子里有"不怕""请休息""抱歉"这类反例，这条规则就当没命中。
            if (not is not null)
            {
                var blocked = false;

                foreach (var bad in not)
                {
                    if (line.Contains(bad, StringComparison.Ordinal))
                    {
                        blocked = true;
                        break;
                    }
                }

                if (blocked)
                    continue;
            }

            var hit = false;

            foreach (var key in keys)
            {
                if (line.Contains(key, StringComparison.Ordinal))
                {
                    hit = true;
                    break;
                }
            }

            if (!hit)
                continue;

            foreach (var candidate in actions)
            {
                var resolved = Resolve(candidate);
                if (resolved is not null)
                    return resolved;
            }

            // 关键词命中了，但候选动作在表里一个都不存在 → 跳过这条规则继续找，
            // 绝不退化成"随便挑一个"。
        }

        return null;
    }

    /// <summary>
    /// 候选词 → 表里真实存在的动作名。先精确相等，再"名字里包含"。
    /// 都对不上返回 null。
    /// </summary>
    private static string? Resolve(string candidate)
    {
        foreach (var name in _available)
        {
            if (string.Equals(name, candidate, StringComparison.Ordinal))
                return name;
        }

        foreach (var name in _available)
        {
            if (name.Contains(candidate, StringComparison.Ordinal))
                return name;
        }

        return null;
    }
