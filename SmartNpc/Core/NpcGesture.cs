    // 开心 / 生气 / 叉腰 / 叹气 / 无奈 / 抱臂 / 抱紧 / 鼓掌 / 助威 / 握拳」有二十来个
    // 根本不在表里 —— 它们既播不出来，时长分档也就永远落不到现在真在用的那些动作上。
    private static readonly string[] QuickGestures =
