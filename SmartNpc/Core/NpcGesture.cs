    /// 规则表负责"合不合适"，这个百分数负责"别每句都比划"。
    /// 面板可调。</para>
    /// </summary>
    ///
    /// <para>v0.18.53：用户说"动作的运用上再多一点点" → 60 提到 <b>72</b>。</para>
    /// </summary>
    public static float ChancePercent { get; set; } = 72f;

    /// <summary>两个动作之间的最小间隔（秒）。调大 = 她更安静，只在关键句上比划。</summary>
    public static float MinGapSeconds { get; set; } = 6f;

    // ── v0.18.53：每个动作该播多久（修「摇头摇两遍」）────────────────
    //
    // 【用户反馈】"现在有的那些动作表情其中有个摇头的动作不要重复两遍"。
    //
    // 根因不是播了两次 —— 是**播得太久**：表情走的是 BaseOverride（基底动画），
    // 基底是**会循环**的。摇头那条时间轴大约 1 秒摇一次，而我们一律给 2.2 秒
    // → 正好摇满两遍。点头 / 摆手 / 鞠躬 / 挥手同理。
    //
    // 修法：**按时长分档**。
    //   · 一下就完事的（摇头 / 点头 / 摆手 / 鞠躬 / 害羞 / 指 / 飞吻 / 表情：× …）→ 1.15 秒；
    //   · 需要时间铺开的（坐下 / 拥抱 / 哭泣 / 欢呼 / 伸懒腰 …）→ 2.6 秒；
    // · 没列出的走默认 2.2 秒。
    //
